// @vitest-environment jsdom
import { act, createElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import pack from './workflow-art/sfx-showcase-pack-v1.provenance.json';
import { SfxUploadShowcase } from './sfx-upload-showcase';
let root: Root; let element: HTMLDivElement;
beforeEach(() => {
  vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT', true);
  vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue(undefined);
  vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {});
  element = document.createElement('div'); document.body.append(element); root = createRoot(element);
});
afterEach(async () => { await act(async () => root.unmount()); element.remove(); vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it('offers one control for the complete packaged library and stops playback on close', async () => {
  await act(async () => root.render(createElement(SfxUploadShowcase, { locale: 'zh' })));
  expect(pack.count).toBe(32);
  expect(element.querySelectorAll('button')).toHaveLength(1);
  expect(element.textContent).not.toMatch(/\d|全部/);
  const audio = element.querySelector('audio')!;
  const video = element.querySelector('video')!;
  expect(video.muted).toBe(true);
  expect(video.loop).toBe(true);
  const audioPlay = vi.fn(async () => {}); audio.play = audioPlay;
  const audioPause = vi.fn(); audio.pause = audioPause;
  const videoPause = vi.fn(); video.pause = videoPause;
  expect(audio.src).toContain('sfx-showcase-pack-v1.wav');
  const play = element.querySelector<HTMLButtonElement>('.relative button[aria-label="播放音效"]')!;
  await act(async () => play.click());
  expect(audioPlay).toHaveBeenCalledOnce();
  expect(element.querySelector('button[aria-label="暂停音效"]')).not.toBeNull();
  await act(async () => { audio.currentTime = 1; audio.dispatchEvent(new Event('timeupdate')); });
  expect(element.querySelector('[data-sfx-mg-cue]')).not.toBeNull();
  expect(element.querySelector('[data-sfx-mg-playhead]')).not.toBeNull();
  await act(async () => element.querySelector<HTMLButtonElement>('button[aria-label="暂停音效"]')!.click());
  expect(audioPause).toHaveBeenCalledOnce();
  await act(async () => root.unmount());
  expect(audioPause).toHaveBeenCalledTimes(2);
  expect(videoPause).toHaveBeenCalled();
  root = createRoot(element);
});
