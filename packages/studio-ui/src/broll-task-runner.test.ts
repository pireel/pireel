import { beforeEach, afterEach, expect, it, vi } from 'vitest';
import type { CaptionTaskRecord } from './caption-task-store';
const mocks = vi.hoisted(() => ({ render: vi.fn(), fetch: vi.fn(), asr: vi.fn(), visual: vi.fn() }));
vi.mock('./media', () => ({ transcribeFile: mocks.asr, durableFileSig: async () => 'output-sig' }));
vi.mock('./local-media', () => ({ saveLocalVideo: async () => true, loadLocalVideo: async () => null }));
vi.mock('./caption-task-store', () => ({ loadCaptionMedia: async () => new File(['footage'], 'asset.mp4', { type: 'video/mp4' }) }));
vi.mock('./client-export', () => ({ clientExportVideo: mocks.render }));
vi.mock('./visual', () => ({ prepareVisualAnalysis: mocks.visual }));
vi.mock('./web-fonts', () => ({ loadFont: async () => {} }));
import { runBrollTask } from './broll-task-runner';
const fixture = (): CaptionTaskRecord => ({ id: 'task', scope: 'owner', scene: 'broll', name: 'source.mp4', sourceSig: 'original', durationSec: 20, width: 1920, height: 1080, stage: 'ready', updatedAt: 1, options: { presetId: 'clean', aspect: 'original', shortenPauses: false, broll: { captions: true, assets: [{ id: 'asset', sig: 'footage', name: 'asset.mp4', kind: 'video', durationSec: 10, width: 1920, height: 1080 }] } } });
beforeEach(() => {
  vi.clearAllMocks(); vi.stubGlobal('fetch', mocks.fetch);
  mocks.asr.mockResolvedValue([{ text: '打开收纳包', start: 1, end: 6 }]);
  mocks.visual.mockResolvedValue({ prep: { frames: [{ timestamp: 4, base64: 'frame', mime: 'image/jpeg' }], segsAll: [{ start: 0, end: 10 }] } });
  mocks.fetch.mockImplementation(async url => Response.json(String(url).includes('/vlm') ? { desc: '打开收纳包' } : { placements: [{ id: 'broll-0', candidateId: 'asset-0', start: 1, duration: 5 }] }));
  mocks.render.mockResolvedValue(new Blob(['result'], { type: 'video/mp4' }));
});
afterEach(() => vi.unstubAllGlobals());
it('executes analysis and matching in one graph and preserves editable source/footage lanes', async () => {
  const source = new File(['speech'], 'source.mp4'); const hooks = { signal: new AbortController().signal, checkpoint: async () => {}, progress: vi.fn() };
  const result = await runBrollTask(fixture(), source, hooks);
  const options = mocks.render.mock.calls[0][0];
  expect(options.videoFile).toBe(source);
  expect(options.visualMediaClips).toEqual([expect.objectContaining({ startSec: 1, endSec: 6, sourceInSec: 2, sourceOutSec: 7, muted: true, audioMuted: true })]);
  expect(options.clipFiles.has(options.visualMediaClips[0].source)).toBe(true);
  expect(result.task.broll?.outputSig).toBe('output-sig');
  expect(result.task.workflow?.definition.id).toBe('official-broll');
  expect(result.task.workflow?.steps.map(step => step.id)).toEqual(expect.arrayContaining(['analysis', 'match', 'plan', 'broll', 'render']));
  expect(result.task.document?.timeline.tracks.find(track => track.role === 'broll')?.clips).toHaveLength(1);
  expect(Object.values(result.task.document!.assets).map(asset => asset.locator.localSig)).toEqual(expect.arrayContaining(['original', 'footage']));
  result.task.options.broll!.edits = { 'broll-0': { start: 8, duration: 2, sourceIn: 1 } };
  await runBrollTask(result.task, source, hooks);
  expect(mocks.render.mock.calls[1][0].visualMediaClips[0]).toMatchObject({ startSec: 8, endSec: 10, sourceInSec: 1, sourceOutSec: 3 });
  expect(mocks.fetch).toHaveBeenCalledTimes(2); expect(mocks.asr).toHaveBeenCalledOnce();
});
it('keeps the speaker visible without matches and stops cancelled work before analysis', async () => {
  mocks.fetch.mockImplementation(async url => Response.json(String(url).includes('/vlm') ? { desc: 'unrelated landscape' } : { placements: [] }));
  const controller = new AbortController(); const hooks = { signal: controller.signal, checkpoint: async () => {}, progress: vi.fn() };
  await runBrollTask(fixture(), new File(['speech'], 'source.mp4'), hooks);
  expect(mocks.render.mock.calls[0][0].visualMediaClips).toEqual([]);
  controller.abort(); await expect(runBrollTask(fixture(), new File([], 'source.mp4'), hooks)).rejects.toMatchObject({ name: 'AbortError' });
  expect(mocks.fetch).toHaveBeenCalledTimes(2);
});
it('consumes an inserted transform in both native output and scene timeline state', async () => {
  const source = new File(['speech'], 'source.mp4'); const hooks = { signal: new AbortController().signal, checkpoint: async () => {}, progress: vi.fn() };
  const first = await runBrollTask(fixture(), source, hooks);
  const definition = structuredClone(first.task.workflow!.definition);
  const { GENERIC_WORKFLOW_CAPABILITIES } = await import('@pireel/studio-engine/workflow-generic');
  definition.steps.splice(definition.steps.findIndex(step => step.id === 'broll'), 0, { id: 'adjust', capability: 'llm.transform', version: 1, dependsOn: ['match'], arguments: { value: { kind: 'step', stepId: 'match', key: 'value' }, instruction: { kind: 'literal', value: 'Move the placement' }, schema: { kind: 'literal', value: { type: 'object', properties: {}, additionalProperties: true } } } });
  const compose = definition.steps.find(step => step.id === 'broll')!;
  compose.arguments.plan = { kind: 'step', stepId: 'adjust', key: 'value' }; compose.dependsOn = [...compose.dependsOn.filter(id => id !== 'match'), 'adjust'];
  const result = await runBrollTask(first.task, source, { ...hooks, definition, nodes: [{ capability: { ...GENERIC_WORKFLOW_CAPABILITIES[0], environments: ['browser'] }, execute: async args => {
    const plan = structuredClone(args.value) as unknown as { placements: { start: number }[] };
    plan.placements[0].start = 8;
    return { status: 'completed', summary: 'Adjusted', artifact: { kind: 'value', data: { value: plan as never } } };
  } }] });
  expect(mocks.render.mock.calls[1][0].visualMediaClips[0].startSec).toBe(8);
  expect(result.task.broll!.placements![0].start).toBe(8);
  expect(mocks.fetch).toHaveBeenCalledTimes(2);
});
it('runs the official PiP scene and reuses paid analysis when only its template changes', async () => {
  const task = fixture(); task.scene = 'pip'; task.options.broll!.pip = { template: 'presenter' };
  const source = new File(['speech'], 'source.mp4'); const hooks = { signal: new AbortController().signal, checkpoint: async () => {}, progress: vi.fn() };
  const first = await runBrollTask(task, source, hooks);
  expect(first.task.workflow?.definition.id).toBe('official-pip');
  const visuals = mocks.render.mock.calls[0][0].visualMediaClips;
  expect(visuals).toHaveLength(2);
  expect(visuals[1]).toMatchObject({ trackId: 'broll-pip-presenter', startSec: 1, endSec: 6, sourceInSec: 1, sourceOutSec: 6, audioMuted: true });
  first.task.options.broll!.pip = { template: 'dim' };
  await runBrollTask(first.task, source, hooks);
  expect(mocks.fetch).toHaveBeenCalledTimes(2); expect(mocks.asr).toHaveBeenCalledOnce();
  expect(mocks.render.mock.calls[1][0].visualMediaClips).toHaveLength(1);
  expect(mocks.render.mock.calls[1][0].comp.blocks.some((block: { label?: string }) => block.label === '画中画背景')).toBe(true);
});
